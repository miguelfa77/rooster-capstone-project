// Generates src/lib/api-types.ts from ../api/openapi.json.
// `--check` exits 1 if the committed file is stale instead of writing it.
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const specUrl = new URL("../../api/openapi.json", import.meta.url);
const outUrl = new URL("../src/lib/api-types.ts", import.meta.url);
const header = "// Generated by scripts/gen-types.mjs from api/openapi.json. Do not edit.\n\n";

const spec = JSON.parse(readFileSync(specUrl, "utf8"));
const generated = header + astToString(await openapiTS(spec));

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outUrl, "utf8");
  } catch {}
  if (current !== generated) {
    console.error("src/lib/api-types.ts is stale; run `npm run gen:types`.");
    process.exit(1);
  }
  console.log("src/lib/api-types.ts is up to date.");
} else {
  writeFileSync(outUrl, generated);
  console.log("Wrote src/lib/api-types.ts");
}
